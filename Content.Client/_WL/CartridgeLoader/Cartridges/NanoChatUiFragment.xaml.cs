    public void UpdateState(NanoChatUiState state)
    {
        var shouldFollowBottom = ShouldFollowBottom(state);
        var selectedConversation = _selectedConversation;
        var stateConversation = GetStateConversation(state);
        var selectionConfirmed = selectedConversation != null && selectedConversation == stateConversation;
        var keepRenderedConversation = selectionConfirmed &&
                                       _state is { } previous &&
                                       CanKeepRenderedConversation(previous, state, selectedConversation.GetValueOrDefault());

        if (selectionConfirmed ||
            _selectedConversation is { } unavailable && !HasConversation(state, unavailable))
            _selectedConversation = null;

        if (_pendingNewChat is { } pending)
        {
            if (state.CurrentChat == pending && state.Recipients.ContainsKey(pending))
            {
                _viewMode = NanoChatViewMode.Chats;
                NumberInput.Clear();
            }

            _pendingNewChat = null;
        }

        _state = state;

        if (_loadingOlder)
        {
            _loadingOlder = false;
            Rebuild();
            _restoreScrollAfterPrepend = true;
            return;
        }

        if (shouldFollowBottom)
            RequestScrollToBottom();

        Rebuild(!keepRenderedConversation);
    }

