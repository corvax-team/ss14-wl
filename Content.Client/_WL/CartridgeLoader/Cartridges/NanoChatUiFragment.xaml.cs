    private void RebuildMessages()
    {
        var state = _state;
        if (state is null)
            return;

        MessageList.RemoveAllChildren();

        var activeConversation = GetActiveConversation();
        if (_deleteConfirmation != activeConversation)
            ResetDeleteConfirmation();

        var hasChats = state.Recipients.Count > 0 || state.Groups.Count > 0;
        var focusComposer = activeConversation is not null && !MessageInputContainer.Visible;
        WelcomeView.Visible = !hasChats;
        ChatView.Visible = hasChats;
        NoConversationSelectedView.Visible = hasChats && activeConversation is null;
        ConversationView.Visible = activeConversation is not null && _viewMode != NanoChatViewMode.Settings;
        ConversationSettingsView.Visible = activeConversation is not null && _viewMode == NanoChatViewMode.Settings;
        MessageInputContainer.Visible = activeConversation is not null;

        if (focusComposer)
            MessageInput.GrabKeyboardFocus();

        WelcomeTitle.Text = Loc.GetString("nanochat-welcome-title");
        WelcomeTitle.FontColorOverride = AccentColor;
        WelcomeDetails.Text = Loc.GetString("nanochat-welcome-details");
        WelcomeLookupButton.Text = Loc.GetString("nanochat-welcome-find-contact");
        NoConversationSelectedLabel.Text = Loc.GetString("nanochat-select-chat");
        NoConversationSelectedLabel.FontColorOverride = AccentColor;
        NoConversationSelectedDetails.Text = Loc.GetString("nanochat-select-chat-details");

        if (activeConversation is not { } current)
            return;

        if (current.Type == NanoChatConversationType.Direct)
        {
            var hasRecipient = state.Recipients.TryGetValue(current.Id, out var selectedRecipient);
            CurrentChatDetails.Text = hasRecipient && selectedRecipient.JobTitle is { } jobTitle
                ? $"{jobTitle} · #{current.Id:D4}"
                : $"#{current.Id:D4}";
            CurrentChatDetails.ToolTip = hasRecipient
                ? selectedRecipient.Name
                : Loc.GetString("nanochat-unknown-contact");
            DeleteChatButton.Visible = true;
        }
        else
        {
            var group = state.Groups[current.Id];
            CurrentChatDetails.Text = $"{group.Name} · {group.Members.Count}/{NanoChatGroup.MaxMembers}";
            CurrentChatDetails.ToolTip = group.Name;
            DeleteChatButton.Visible = false;
        }
        CurrentChatHeader.PanelOverride = HeaderPanel;
        CurrentChatHeader.ModulateSelfOverride = null;
        if (_deleteConfirmation == null)
            DeleteChatButton.ToolTip = Loc.GetString("nanochat-delete-chat");
        UpdateComposerState(MessageInput.Text);

        if (_lastRenderedConversation != current)
            RequestScrollToBottom();

        var messages = current.Type == NanoChatConversationType.Direct
            ? state.Messages.GetValueOrDefault(current.Id)
            : state.GroupMessages.GetValueOrDefault(current.Id);
        if (messages == null || messages.Count == 0)
        {
            MessageList.AddChild(new Label
            {
                Text = Loc.GetString("nanochat-no-messages"),
                HorizontalAlignment = HAlignment.Center,
                Margin = new Thickness(4),
                StyleClasses = { "LabelSubText" },
            });
            RequestScrollToBottom();
            return;
        }

        foreach (var message in messages)
        {
            var own = message.Sender == state.OwnNumber;
            var row = new BoxContainer
            {
                Orientation = LayoutOrientation.Horizontal,
                HorizontalExpand = true,
            };
            if (own)
                row.AddChild(new BoxContainer { HorizontalExpand = true });
            var card = new PanelContainer
            {
                MinWidth = 84,
                MaxWidth = MessageBubbleMaxWidth,
                Margin = new Thickness(1),
                PanelOverride = own ? OutgoingMessagePanel : IncomingMessagePanel,
                ModulateSelfOverride = own ? Color.FromHex("#C2D9E6") : Color.FromHex("#B8C0C9"),
                StyleClasses = { "AngleRect" },
            };
            var contents = new BoxContainer { Orientation = LayoutOrientation.Vertical, Margin = new Thickness(8, 6, 8, 5) };
            if (current.Type == NanoChatConversationType.Group && !own)
            {
                var senderName = state.Groups[current.Id].Members.TryGetValue(message.Sender, out var senderMember)
                    ? ShortenDisplayName(senderMember.Name)
                    : $"#{message.Sender:D4}";
                contents.AddChild(new Label
                {
                    Text = senderName,
                    StyleClasses = { "LabelSubText" },
                    FontColorOverride = AccentColor,
                    ClipText = true,
                    ToolTip = senderName,
                    Margin = new Thickness(0, 0, 0, 2),
                });
            }
            var messageLabel = new RichTextLabel
            {
                MaxWidth = MessageBubbleMaxWidth - 22f,
                HorizontalExpand = true,
            };
            messageLabel.SetMessage(
                FormattedMessage.FromMarkupPermissive(message.Content),
                UserFormattableTags.BaseAllowedTags,
                MessageTextColor);
            contents.AddChild(messageLabel);
            contents.AddChild(new Label
            {
                Text = FormatMessageStatus(message),
                StyleClasses = { "LabelSubText" },
                HorizontalAlignment = HAlignment.Right,
                FontColorOverride = DimTextColor,
                Margin = new Thickness(0, 3, 0, 0),
            });
            card.AddChild(contents);
            row.AddChild(card);
            if (!own)
                row.AddChild(new BoxContainer { HorizontalExpand = true });
            MessageList.AddChild(row);
        }

        _lastRenderedConversation = current;
    }

    private void SubmitMessage()
    {
        if (_state is null)
            return;

        var conversation = GetActiveConversation();
        var text = MessageInput.Text.Trim();
        var plainLength = FormattedMessage.RemoveMarkupPermissive(text).Trim().Length;

        if (conversation is null ||
            plainLength == 0 ||
            plainLength > NanoChatMessage.MaxLength ||
            text.Length > NanoChatMessage.MaxMarkupLength)
            return;

        SendMessage?.Invoke(conversation.Value, text);
        MessageInput.Clear();
        UpdateComposerState(string.Empty);
        RequestScrollToBottom();
    }

    private void UpdateComposerState(string text)
    {
        var length = FormattedMessage.RemoveMarkupPermissive(text).Length;
        var conversation = GetActiveConversation();
        var hasChat = conversation != null;
        var blocked = conversation is { Type: NanoChatConversationType.Direct } direct &&
                      _state?.BlockedNumbers.Contains(direct.Id) == true;
        var tooLong = length > NanoChatMessage.MaxLength || text.Length > NanoChatMessage.MaxMarkupLength;

        SendButton.Disabled = !hasChat || blocked || string.IsNullOrWhiteSpace(text) || tooLong;
        SendButton.ModulateSelfOverride = SendButton.Disabled
            ? Color.FromHex("#59616B")
            : Color.FromHex("#3F5C6C");
        CharacterCount.Visible = tooLong;
        if (tooLong)
            CharacterCount.Text = Loc.GetString("nanochat-message-too-long", ("current", length), ("max", NanoChatMessage.MaxLength));
    }

    private void SubmitStartChat()
    {
        if (!uint.TryParse(NumberInput.Text.Trim(), out var number) || number == _state?.OwnNumber)
            return;

        if (_addingMembersToGroup is { } groupConversation)
        {
            AddGroupMember?.Invoke(groupConversation, number);
            _addingMembersToGroup = null;
            _viewMode = NanoChatViewMode.Settings;
            NumberInput.Clear();
            Rebuild();
            return;
        }

        if (GroupComposer.Visible)
        {
            if (_selectedGroupMembers.Count >= NanoChatGroup.MaxMembers - 1)
                return;

            _selectedGroupMembers.Add(number);
            NumberInput.Clear();
            UpdateGroupComposer();
            RebuildLookup();
            return;
        }

        NanoChatRecipient? directoryEntry = null;
        if (_state?.Directory is { } directory)
        {
            foreach (var candidate in directory)
            {
                if (candidate.Number != number)
                    continue;

                directoryEntry = candidate;
                break;
            }
        }

        if (directoryEntry is { } knownContact)
        {
            RequestNewChat(knownContact);
            return;
        }

        _pendingNewChat = number;
        NewChat?.Invoke(number);
        UpdateStartChatState(NumberInput.Text);
    }

    private void UpdateStartChatState(string text)
    {
        StartChatButton.Disabled = _pendingNewChat != null ||
                                   !uint.TryParse(text.Trim(), out var number) ||
                                   number == _state?.OwnNumber ||
                                   GroupComposer.Visible && _selectedGroupMembers.Count >= NanoChatGroup.MaxMembers - 1;
    }

    private void RequestNewChat(NanoChatRecipient recipient)
    {
        if (_pendingNewChat != null)
            return;

        _pendingNewChat = recipient.Number;
        NewChat?.Invoke(recipient.Number);
        UpdateStartChatState(NumberInput.Text);
    }

    private string GetLastMessagePreview(NanoChatConversationId conversation)
    {
        var messages = GetMessages(_state!, conversation);
        if (messages is { Count: > 0 })
        {
            var message = messages[^1];
            var plain = FormattedMessage.RemoveMarkupPermissive(message.Content);
            return message.Sender == _state!.OwnNumber
                ? Loc.GetString("nanochat-message-preview-own", ("message", plain))
                : plain;
        }

        return Loc.GetString("nanochat-no-messages");
    }

    internal static string ShortenDisplayName(string name)
    {
        var firstName = name.Split(' ', StringSplitOptions.RemoveEmptyEntries).FirstOrDefault();
        if (string.IsNullOrEmpty(firstName))
            return name;

        var hyphenParts = firstName.Split('-', StringSplitOptions.RemoveEmptyEntries);
        if (hyphenParts.Length > 2)
            return $"{hyphenParts[0]}-{hyphenParts[1]}";

        return firstName;
    }

    internal static string FormatDirectDisplayName(string name)
    {
        var parts = name.Split(' ', StringSplitOptions.RemoveEmptyEntries);
        if (parts.Length == 0)
            return name;

        var firstName = ShortenDisplayName(parts[0]);
        if (parts.Length == 1)
            return firstName;

        var surname = parts[^1];
        return surname.Length == 0 ? firstName : $"{firstName} {surname[0]}.";
    }

    private static string FormatListText(string text)
    {
        const int maxCharacters = 28;
        return text.Length <= maxCharacters ? text : text[..(maxCharacters - 1)] + "…";
    }

    private static string FormatLookupText(NanoChatRecipient recipient)
    {
        var details = recipient.JobTitle is { Length: > 0 }
            ? $"{recipient.JobTitle} · #{recipient.Number:D4}"
            : $"#{recipient.Number:D4}";

        const int maxCharacters = 30;
        return details.Length <= maxCharacters ? details : details[..(maxCharacters - 1)] + "…";
    }

