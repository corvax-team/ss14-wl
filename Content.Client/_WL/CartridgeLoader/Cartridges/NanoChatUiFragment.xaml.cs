    private void RebuildLookup()
    {
        LookupList.RemoveAllChildren();
        UpdateStartChatState(NumberInput.Text);
        CreateGroupButton.Visible = _addingMembersToGroup == null;

        var directory = _state?.Directory;
        if (directory is null || directory.Count == 0)
        {
            LookupList.AddChild(CreateDirectoryEmptyLabel());
            return;
        }

        var anyEntries = false;
        var query = DirectorySearchInput.Text.Trim();

        foreach (var recipient in directory)
        {
            if (_state!.OwnNumber == recipient.Number ||
                (_addingMembersToGroup is { } addingTo &&
                 _state.Groups.TryGetValue(addingTo.Id, out var targetGroup) &&
                 targetGroup.Members.ContainsKey(recipient.Number)) ||
                (query.Length > 0 &&
                 !recipient.Name.Contains(query, StringComparison.CurrentCultureIgnoreCase) &&
                 !(recipient.JobTitle?.Contains(query, StringComparison.CurrentCultureIgnoreCase) ?? false)))
                continue;

            anyEntries = true;

            var button = new Button
            {
                HorizontalExpand = true,
                ToolTip = recipient.JobTitle is { } job
                    ? $"{recipient.Name} ({job})  #{recipient.Number:D4}"
                    : $"{recipient.Name}  #{recipient.Number:D4}",
                Pressed = GroupComposer.Visible && _selectedGroupMembers.Contains(recipient.Number),
                ToggleMode = GroupComposer.Visible,
            };
            if (GroupComposer.Visible &&
                _selectedGroupMembers.Count >= NanoChatGroup.MaxMembers - 1 &&
                !_selectedGroupMembers.Contains(recipient.Number))
                button.Disabled = true;

            var row = new BoxContainer
            {
                Orientation = LayoutOrientation.Horizontal,
                HorizontalExpand = true,
                Margin = new Thickness(4, 2),
                SeparationOverride = 4,
            };
            row.AddChild(CreateJobIcon(recipient.JobIcon));

            var labels = new BoxContainer
            {
                Orientation = LayoutOrientation.Vertical,
                HorizontalExpand = true,
            };
            labels.AddChild(new Label
            {
                Text = FormatListText(recipient.Name),
                HorizontalExpand = true,
                ClipText = true,
                ToolTip = recipient.Name,
            });
            labels.AddChild(new Label
            {
                Text = FormatLookupText(recipient),
                StyleClasses = { "LabelSubText" },
                HorizontalExpand = true,
                ClipText = true,
                ToolTip = button.ToolTip,
            });
            row.AddChild(labels);
            button.AddChild(row);

            button.OnPressed += _ =>
            {
                if (_addingMembersToGroup is { } groupConversation)
                {
                    AddGroupMember?.Invoke(groupConversation, recipient.Number);
                    _addingMembersToGroup = null;
                    _viewMode = NanoChatViewMode.Settings;
                    Rebuild();
                }
                else if (GroupComposer.Visible)
                {
                    if (!_selectedGroupMembers.Contains(recipient.Number) &&
                        _selectedGroupMembers.Count >= NanoChatGroup.MaxMembers - 1)
                        return;

                    if (!_selectedGroupMembers.Add(recipient.Number))
                        _selectedGroupMembers.Remove(recipient.Number);
                    UpdateGroupComposer();
                    RebuildLookup();
                }
                else
                {
                    RequestNewChat(recipient);
                }
            };
            LookupList.AddChild(button);
        }

        if (!anyEntries)
            LookupList.AddChild(CreateDirectoryEmptyLabel());
    }

    private void RebuildChatList()
    {
        ChatList.RemoveAllChildren();

        var contacts = _state!.Recipients.Values.OrderBy(recipient => recipient.Name).ToList();
        var groups = _state.Groups.Values.OrderBy(group => group.Name).ToList();

        NoChatsLabel.Text = Loc.GetString("nanochat-no-chats");
        NoChatsLabel.Visible = contacts.Count == 0 && groups.Count == 0;

        if (contacts.Count == 0 && groups.Count == 0)
        {
            ChatList.AddChild(NoChatsLabel);
            return;
        }

        foreach (var recipient in contacts)
        {
            var conversation = new NanoChatConversationId(NanoChatConversationType.Direct, recipient.Number);
            ChatList.AddChild(CreateConversationButton(
                conversation,
                FormatDirectDisplayName(recipient.Name),
                recipient.Name,
                recipient.HasUnread));
        }

        foreach (var group in groups)
        {
            var conversation = new NanoChatConversationId(NanoChatConversationType.Group, group.Id);
            ChatList.AddChild(CreateConversationButton(
                conversation,
                group.Name,
                group.Name,
                group.HasUnread,
                CreateFixedIcon(GroupTexture, 19, 24, HAlignment.Left)));
        }
    }

