    private bool ShouldFollowBottom(NanoChatUiState nextState)
    {
        var previousState = _state;
        var previousConversation = _selectedConversation ?? (previousState == null ? null : GetStateConversation(previousState));
        var nextConversation = _selectedConversation ?? GetStateConversation(nextState);

        if (nextConversation == null)
            return previousConversation != null;

        if (previousConversation != nextConversation)
            return true;

        if (previousState == null)
            return true;

        var previousMessages = GetMessages(previousState, nextConversation.Value);
        var nextMessages = GetMessages(nextState, nextConversation.Value);

        if (!HasNewLatestMessage(previousMessages, nextMessages))
            return false;

        var latestMessage = nextMessages![^1];
        var viewportBottom = MessagesScroll.VScrollTarget + MessagesScroll.Size.Y;
        return ShouldFollowNewMessage(
            latestMessage.Sender,
            nextState.OwnNumber,
            MessageList.Size.Y,
            viewportBottom);
    }

    /// <summary>
    ///     Detects a newly appended message by identity instead of list length. Once a page is full,
    ///     the server sends a sliding window whose size stays constant while its newest item changes.
    /// </summary>
    internal static bool HasNewLatestMessage(
        IReadOnlyList<NanoChatMessage>? previousMessages,
        IReadOnlyList<NanoChatMessage>? nextMessages)
    {
        if (nextMessages is not { Count: > 0 })
            return false;

        return previousMessages is not { Count: > 0 } ||
               !nextMessages[^1].Equals(previousMessages[^1]);
    }

    /// <summary>
    ///     Decides whether a new message should move the viewport. The dimensions must describe the
    ///     existing list before it is rebuilt, so an incoming message cannot change this decision.
    /// </summary>
    internal static bool ShouldFollowNewMessage(
        uint sender,
        uint ownNumber,
        float contentHeight,
        float viewportBottom)
    {
        if (sender == ownNumber)
            return true;

        return contentHeight - viewportBottom <= FollowBottomThreshold;
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        if (!MessagesScroll.Visible)
            return;

        if (_restoreScrollAfterPrepend)
        {
            if (!MessageList.IsMeasureValid || !MessagesScroll.IsArrangeValid)
                return;

            _restoreScrollAfterPrepend = false;
            MessagesScroll.VScrollTarget = Math.Max(0, MessageList.Size.Y - _historyHeightBeforeLoad);
            return;
        }

        if (!_scrollToBottom)
            return;

        // UI frame updates run before queued layout updates. Keep the request until the newly
        // rebuilt message list has been measured and the scroll range reflects its final height.
        if (!MessageList.IsMeasureValid || !MessagesScroll.IsArrangeValid)
            return;

        _scrollToBottom = false;
        MessagesScroll.VScrollTarget = float.PositiveInfinity;
    }

    private void TryLoadOlderMessages()
    {
        if (_loadingOlder || MessagesScroll.VScrollTarget > 2f || GetActiveConversation() is not { } conversation ||
            _state?.HasOlderMessages.Contains(conversation) != true)
            return;

        _loadingOlder = true;
        _historyHeightBeforeLoad = MessageList.Size.Y;
        LoadOlderMessages?.Invoke(conversation);
    }

    private NanoChatConversationId? GetActiveConversation()
    {
        if (_selectedConversation is { } selected)
            return selected;
        return _state == null ? null : GetStateConversation(_state);
    }

    private static NanoChatConversationId? GetStateConversation(NanoChatUiState state)
    {
        if (state.CurrentGroup is { } group)
            return new NanoChatConversationId(NanoChatConversationType.Group, group);
        if (state.CurrentChat is { } chat)
            return new NanoChatConversationId(NanoChatConversationType.Direct, chat);
        return null;
    }

    private static bool HasConversation(NanoChatUiState state, NanoChatConversationId conversation)
        => conversation.Type == NanoChatConversationType.Direct
            ? state.Recipients.ContainsKey(conversation.Id)
            : state.Groups.ContainsKey(conversation.Id);

    private static List<NanoChatMessage>? GetMessages(NanoChatUiState state, NanoChatConversationId conversation)
        => conversation.Type == NanoChatConversationType.Direct
            ? state.Messages.GetValueOrDefault(conversation.Id)
            : state.GroupMessages.GetValueOrDefault(conversation.Id);

    private static string FormatMessageStatus(NanoChatMessage message)
    {
        var time = message.Timestamp.ToString(@"hh\:mm");
        if (message.IntendedRecipients > 0 && message.DeliveredRecipients < message.IntendedRecipients)
            return message.DeliveredRecipients == 0
                ? Loc.GetString("nanochat-message-status-failed", ("time", time))
                : Loc.GetString("nanochat-message-status-partial",
                    ("time", time),
                    ("delivered", message.DeliveredRecipients),
                    ("total", message.IntendedRecipients));
        return message.DeliveryFailed
            ? Loc.GetString("nanochat-message-status-failed", ("time", time))
            : time;
    }

    private static bool CanKeepRenderedConversation(
        NanoChatUiState previous,
        NanoChatUiState next,
        NanoChatConversationId conversation)
    {
        if (!HasConversation(previous, conversation) || !HasConversation(next, conversation))
            return false;

        if (conversation.Type == NanoChatConversationType.Direct)
        {
            var oldRecipient = previous.Recipients[conversation.Id];
            var newRecipient = next.Recipients[conversation.Id];
            if (oldRecipient.Name != newRecipient.Name || oldRecipient.JobTitle != newRecipient.JobTitle)
                return false;
        }
        else
        {
            var oldGroup = previous.Groups[conversation.Id];
            var newGroup = next.Groups[conversation.Id];
            if (oldGroup.Name != newGroup.Name ||
                oldGroup.Members.Count != newGroup.Members.Count ||
                oldGroup.Members.Any(pair =>
                    !newGroup.Members.TryGetValue(pair.Key, out var member) ||
                    pair.Value.Name != member.Name))
                return false;
        }

        var previousMessages = GetMessages(previous, conversation);
        var nextMessages = GetMessages(next, conversation);
        if (previousMessages == null || nextMessages == null)
            return previousMessages == nextMessages;

        return previousMessages.SequenceEqual(nextMessages);
    }
