    private void RebuildGroupSettings(NanoChatConversationId conversation)
    {
        if (_state == null)
            return;

        if (!_state.Groups.TryGetValue(conversation.Id, out var group) ||
            !group.Members.TryGetValue(_state.OwnNumber, out var ownMember))
            return;

        SettingsTitle.Text = $"{group.Name} · {group.Members.Count}/{NanoChatGroup.MaxMembers}";
        GroupRenameRow.Visible = ownMember.IsAdmin;
        if (_groupNameDraftFor != group.Id)
        {
            GroupNameInput.Text = group.Name;
            _groupNameDraftFor = group.Id;
        }
        RenameGroupButton.Text = Loc.GetString("nanochat-group-rename");
        MuteConversationButton.Visible = true;
        MuteConversationButton.Text = Loc.GetString(group.NotificationsMuted
            ? "nanochat-group-unmute"
            : "nanochat-group-mute");
        LeaveOrBlockButton.Text = Loc.GetString("nanochat-group-leave");
        DeleteGroupButton.Visible = ownMember.IsAdmin;
        DeleteGroupButton.Text = Loc.GetString("nanochat-group-delete");

        if (ownMember.IsAdmin && group.Members.Count < NanoChatGroup.MaxMembers)
        {
            var addButton = new Button { Text = Loc.GetString("nanochat-group-add-member"), HorizontalExpand = true };
            addButton.OnPressed += _ =>
            {
                _addingMembersToGroup = conversation;
                _viewMode = NanoChatViewMode.Lookup;
                Rebuild();
            };
            ConversationSettingsList.AddChild(addButton);
        }

        foreach (var member in group.Members.Values.OrderByDescending(member => member.IsAdmin).ThenBy(member => member.Name))
            ConversationSettingsList.AddChild(CreateGroupMemberRow(conversation, member, ownMember.IsAdmin));
    }

