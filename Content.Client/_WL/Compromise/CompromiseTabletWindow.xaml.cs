namespace Content.Client._WL.Compromise;

[GenerateTypedNameReferences]
public sealed partial class CompromiseTabletWindow : FancyWindow
{
    [Dependency] private IEntityManager _entMan = default!;
    [Dependency] private IPrototypeManager _protoMan = default!;

    private readonly SpriteSystem _spriteSystem;

    public readonly EntityUid Tablet;

    public Action<uint?>? OnKeySelected;
    public Action<StationRecordFilterType, string>? OnFiltersChanged;
    public Action<uint>? OnPrinted;

    private uint _maxLength;
    private uint? _selectedKey;
    private CompromiseRecord? _selectedRecord;

    private StationRecordFilterType _currentFilterType;

    public CompromiseTabletWindow(EntityUid tablet, uint maxLength)
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        _spriteSystem = _entMan.System<SpriteSystem>();

        Tablet = tablet;

        _maxLength = maxLength;
        _currentFilterType = StationRecordFilterType.Name;

        OpenCentered();

        foreach (var item in Enum.GetValues<StationRecordFilterType>())
        {
            FilterType.AddItem(GetTypeFilterLocals(item), (int)item);
        }

        RecordListing.OnItemSelected += args =>
        {
            if (RecordListing[args.ItemIndex].Metadata is not uint cast)
                return;

            OnKeySelected?.Invoke(cast);
        };

        RecordListing.OnItemDeselected += _ =>
        {
            OnKeySelected?.Invoke(null);
        };

        FilterType.OnItemSelected += eventArgs =>
        {
            var type = (StationRecordFilterType)eventArgs.Id;

            if (_currentFilterType != type)
            {
                _currentFilterType = type;
                FilterListingOfRecords(FilterText.Text);
            }
        };

        FilterText.OnTextEntered += args =>
        {
            FilterListingOfRecords(args.Text);
        };

        PrintButton.OnPressed += _ =>
        {
            PrintButton.Disabled = true;
            if (_selectedKey != null)
                OnPrinted?.Invoke(_selectedKey.Value);
        };
    }

    public void UpdateState(CompromiseTabletState state)
    {
        if (state.Filter is {} filter)
        {
            if (filter.Type != _currentFilterType)
                _currentFilterType = filter.Type;

            if (filter.Value != FilterText.Text)
                FilterText.Text = filter.Value;
        }

        PrintButton.Disabled = !state.CanPrint;

        _selectedKey = state.SelectedKey;
        FilterType.SelectId((int)_currentFilterType);
        NoRecords.Visible = state.RecordListing == null || state.RecordListing.Count == 0;
        PopulateRecordListing(state.RecordListing);

        var selected = _selectedKey is not null;

        RecordUnselected.Visible = !selected;
        PersonContainer.Visible = selected;

        if (state is { Record: not null, StationRecord: not null })
        {
            PopulateRecordContainer(state.StationRecord, state.Record);
            _selectedRecord = state.Record;
        }
        else
        {
            PersonContainer.Visible = false;
            _selectedRecord = null;
        }
    }

    private void PopulateRecordListing(Dictionary<uint, string>? listing)
    {
        if (listing == null)
        {
            RecordListing.Clear();
            return;
        }

        var entries = listing.Select(i => new ItemList.Item(RecordListing) {
                Text = i.Value,
                Metadata = i.Key
        }).ToList();
        entries.Sort((a, b) => string.Compare(a.Text, b.Text, StringComparison.Ordinal));
        RecordListing.SetItems(entries, (a,b) => string.Compare(a.Text, b.Text));
    }

    private void PopulateRecordContainer(GeneralStationRecord stationRecord, CompromiseRecord record)
    {
        var specifier = new SpriteSpecifier.Rsi(new ResPath("Interface/Misc/job_icons.rsi"), "Unknown");
        var na = Loc.GetString("generic-not-available-shorthand");
        PersonName.Text = stationRecord.Name;
        PersonJob.Text = stationRecord.JobTitle ?? na;

        // Job icon
        if (_protoMan.TryIndex<JobIconPrototype>(stationRecord.JobIcon, out var proto))
            PersonJobIcon.Texture = _spriteSystem.Frame0(proto.Icon);
        else
            PersonJobIcon.Texture = _spriteSystem.Frame0(specifier);

        PersonPrints.Text = stationRecord.Fingerprint ?? Loc.GetString("generic-not-available-shorthand");
        PersonDna.Text = stationRecord.DNA ?? Loc.GetString("generic-not-available-shorthand");

        var message = new FormattedMessage();

        if (!record.Valid)
        {
            CompromiseText.SetMessage(FormattedMessage.FromMarkupOrThrow(Loc.GetString("compromise-tablet-empty-record")));
            return;
        }

        foreach (var compromiseId in record.CompromiseData)
        {
            if (!_protoMan.TryIndex<CompromisePrototype>(compromiseId, out var compromise) ||
                    !_protoMan.TryIndex<CompromiseCategoryPrototype>(compromise.Category, out var category))
                continue;

            message.AddText($"{category.LocalizedName}: {compromise.LocalizedName}. {compromise.LocalizedDesc}");
            message.PushNewline();
            message.PushNewline();
        }

        message.AddText(record.CompromiseText);

        CompromiseText.SetMessage(message);
    }

    private void FilterListingOfRecords(string text = "")
    {
        OnFiltersChanged?.Invoke(_currentFilterType, text);
    }

    private string GetTypeFilterLocals(StationRecordFilterType type)
    {
        return Loc.GetString($"criminal-records-{type.ToString().ToLower()}-filter");
    }
}
