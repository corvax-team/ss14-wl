    public void UpdatePoints(ResearchMainConsoleBoundInterfaceState state)
    {
        PointsTypesContainer.Children.Clear();
        PointsValuesContainer.Children.Clear();

        var pointsData = state.PointsData;

        foreach (var (typeId, (curValue, maxValue, psValue)) in pointsData)
        {
            var typeProto = _prototype.Index<ResearchPointsTypePrototype>(typeId);
            var typeLabel = new Label
            {
                Text = typeProto.LocalizedName,
                FontColorOverride = typeProto.Color,
                HorizontalAlignment = Label.HAlignment.Left
            };

            var typeContainer = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Vertical,
                VerticalExpand = true,
                HorizontalExpand = true,
                Margin = new Thickness(4),
                SizeFlagsStretchRatio = 2,
                Children = { typeLabel }
            };

            PointsTypesContainer.AddChild(typeContainer);

            var valuesContainer = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Horizontal,
                VerticalExpand = true,
                HorizontalExpand = true,
                SizeFlagsStretchRatio = 2,
                Margin = new Thickness(10, 1, 0, 0)
            };

            var enumValues = new List<FixedPoint2>();

            enumValues.Add(curValue);
            enumValues.Add(maxValue);
            enumValues.Add(psValue);

            foreach (var value in enumValues)
            {
                var valueBox = new BoxContainer
                {

                    Orientation = BoxContainer.LayoutOrientation.Vertical,
                    VerticalExpand = true,
                    HorizontalExpand = true,
                    Margin = new Thickness(4),
                    MinWidth = 120,
                    Children = { new Label
                        {
                            Text = value.ToString(),
                            FontColorOverride = typeProto.Color,
                            HorizontalAlignment = Label.HAlignment.Center
                        }
                    }
                };

                valuesContainer.AddChild(valueBox);
            }

            PointsValuesContainer.AddChild(valuesContainer);
        }
    }

