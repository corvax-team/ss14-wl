    private void UpdateAcademicTitleVisibility(bool clearHiddenValues)
    {
        var visible = EmploymentAcademicTitle.SelectedId != (int) RecordAcademicTitle.NotApplicable;
        AcademicTitleFieldContainer.Visible = visible;
        AcademicTitleDateContainer.Visible = visible;

        if (visible || !clearHiddenValues)
            return;

        var wasUpdating = _updating;
        _updating = true;
        EmploymentAcademicTitleField.Text = string.Empty;
        EmploymentAcademicTitleDate.SetText(string.Empty);
        _updating = wasUpdating;
    }

    private void AddEducationEntry(EducationRecordData record, bool emit)
    {
        if (_educationEntries.Count >= StructuredCharacterRecords.MaxEducationEntries)
            return;

        var specialty = new LineEdit { Text = record.Specialty, HorizontalExpand = true, MinWidth = 230 };
        var specialtyGroup = new RecordOptionButton { HorizontalExpand = true, MinWidth = 230, MaxWidth = 600 };
        var specialtyGroupValues = new List<string> { string.Empty };
        specialtyGroup.AddItem(Loc.GetString("records-value-not-specified"), 0);
        foreach (var group in StructuredCharacterRecords.SpecialtyGroups)
        {
            specialtyGroupValues.Add(group);
            specialtyGroup.AddItem(Loc.GetString($"records-specialty-group-value-{group}"), specialtyGroupValues.Count - 1);
        }
        var specialtyGroupIndex = specialtyGroupValues.IndexOf(record.SpecialtyGroup);
        if (specialtyGroupIndex < 0 && !string.IsNullOrWhiteSpace(record.SpecialtyGroup))
        {
            specialtyGroupValues.Add(record.SpecialtyGroup);
            specialtyGroupIndex = specialtyGroupValues.Count - 1;
            specialtyGroup.AddItem(record.SpecialtyGroup, specialtyGroupIndex);
        }
        specialtyGroup.SelectId(Math.Max(0, specialtyGroupIndex));
        var specialtySubgroup = new RecordOptionButton { HorizontalExpand = true, MinWidth = 230, MaxWidth = 600 };
        var specialtySubgroupValues = new List<string>();
        void PopulateSpecialtySubgroups(string selected)
        {
            specialtySubgroup.Clear();
            specialtySubgroupValues.Clear();
            specialtySubgroupValues.Add(string.Empty);
            specialtySubgroup.AddItem(Loc.GetString("records-value-not-specified"), 0);

            var selectedGroup = specialtyGroupValues[specialtyGroup.SelectedId];
            foreach (var subgroup in SpecialtyGroupCatalog.GetSubgroups(selectedGroup))
            {
                specialtySubgroupValues.Add(subgroup);
                specialtySubgroup.AddItem(
                    Loc.GetString(SpecialtyGroupCatalog.GetSubgroupLocalizationKey(subgroup)),
                    specialtySubgroupValues.Count - 1);
            }

            var subgroupIndex = specialtySubgroupValues.IndexOf(selected);
            if (subgroupIndex < 0 && !string.IsNullOrWhiteSpace(selected))
            {
                specialtySubgroupValues.Add(selected);
                subgroupIndex = specialtySubgroupValues.Count - 1;
                var displayName = SpecialtyGroupCatalog.ContainsSubgroup(selected)
                    ? Loc.GetString(SpecialtyGroupCatalog.GetSubgroupLocalizationKey(selected))
                    : selected;
                specialtySubgroup.AddItem(displayName, subgroupIndex);
            }

            specialtySubgroup.SelectId(Math.Max(0, subgroupIndex));
        }
        PopulateSpecialtySubgroups(record.SpecialtySubgroup);
        var degree = new RecordOptionButton { HorizontalExpand = true, MinWidth = 230, MaxWidth = 380 };
        PopulateEnumOptions(degree, Enum.GetValues<RecordAcademicDegree>(), "records-degree");
        degree.SelectId((int) record.Degree);
        var institution = new LineEdit { Text = record.Institution, HorizontalExpand = true, MinWidth = 230 };
        var diplomaDate = new RecordDateEdit { HorizontalExpand = true, MinWidth = 230 };
        diplomaDate.SetText(record.DiplomaDate);

        var specialtyField = CreateEducationField("records-specialty", specialty, out var specialtyLabel);
        var specialtyGroupField = CreateEducationField("records-specialty-group", specialtyGroup, out var specialtyGroupLabel);
        var specialtySubgroupField = CreateEducationField("records-specialty-subgroup", specialtySubgroup, out var specialtySubgroupLabel);
        var degreeField = CreateEducationField("records-degree", degree, out var degreeLabel);
        var diplomaDateField = CreateEducationField("records-diploma-date", diplomaDate, out var diplomaDateLabel);
        var institutionField = CreateEducationField("records-institution", institution, out var institutionLabel);

        var firstRow = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            HorizontalExpand = true,
            SeparationOverride = 10,
            Children =
            {
                specialtyField,
                specialtyGroupField,
            },
        };
        var secondRow = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            HorizontalExpand = true,
            SeparationOverride = 10,
            Children =
            {
                specialtySubgroupField,
                degreeField,
            },
        };
        var thirdRow = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            HorizontalExpand = true,
            SeparationOverride = 10,
            Children =
            {
                institutionField,
                diplomaDateField,
            },
        };

        var remove = new Button
        {
            Text = Loc.GetString("records-remove-education"),
            HorizontalAlignment = HAlignment.Left,
            Margin = new Thickness(0, 4, 0, 0),
        };
        var title = new Label
        {
            StyleClasses = { "LabelBig" },
            FontColorOverride = Color.FromHex("#C7C7CC"),
        };
        var content = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            Margin = new Thickness(10),
            SeparationOverride = 6,
            Children = { title, firstRow, secondRow, thirdRow, remove },
        };
        var container = new PanelContainer
        {
            HorizontalExpand = true,
            HorizontalAlignment = HAlignment.Stretch,
            MaxWidth = 1260,
            Margin = new Thickness(0, 4),
            PanelOverride = new StyleBoxFlat
            {
                BackgroundColor = Color.FromHex("#18181C"),
                BorderColor = Color.FromHex("#46464E"),
                BorderThickness = new Thickness(1),
            },
            Children = { content },
        };
        var controls = new EducationEntryControls(
            container,
            title,
            firstRow,
            secondRow,
            thirdRow,
            [
                new EducationFieldLabel(specialtyLabel, "records-specialty"),
                new EducationFieldLabel(specialtyGroupLabel, "records-specialty-group"),
                new EducationFieldLabel(specialtySubgroupLabel, "records-specialty-subgroup"),
                new EducationFieldLabel(degreeLabel, "records-degree"),
                new EducationFieldLabel(institutionLabel, "records-institution"),
                new EducationFieldLabel(diplomaDateLabel, "records-diploma-date"),
            ],
            specialty,
            specialtyGroup,
            specialtyGroupValues,
            specialtySubgroup,
            specialtySubgroupValues,
            degree,
            institution,
            diplomaDate);
        _educationEntries.Add(controls);
        EducationEntries.AddChild(container);

        BindLineEdit(specialty, EmitEmployment);
        BindLineEdit(institution, EmitEmployment);
        diplomaDate.OnDateChanged += EmitEmployment;
        degree.OnItemSelected += args =>
        {
            degree.SelectId(args.Id);
            EmitEmployment();
        };
        specialtyGroup.OnItemSelected += args =>
        {
            specialtyGroup.SelectId(args.Id);
            PopulateSpecialtySubgroups(string.Empty);
            EmitEmployment();
        };
        specialtySubgroup.OnItemSelected += args =>
        {
            specialtySubgroup.SelectId(args.Id);
            EmitEmployment();
        };
        remove.OnPressed += _ =>
        {
            controls.Container.Orphan();
            _educationEntries.Remove(controls);
            RenumberEducationEntries();
            UpdateEducationButton();
            EmitEmployment();
        };

        RenumberEducationEntries();
        UpdateEducationLayout();
        UpdateEducationButton();
        if (emit)
            EmitEmployment();
    }

    private BoxContainer CreateEducationField(string labelKey, Control input, out Label label)
    {
        label = new Label
        {
            Text = Loc.GetString(labelKey),
            StyleClasses = { "LabelSubText" },
            Margin = new Thickness(0, 0, 0, 2),
        };
        return new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            HorizontalExpand = true,
            MinWidth = 250,
            Children =
            {
                label,
                input,
            },
        };
    }

    private void UpdateEducationButton()
    {
        AddEducation.Disabled = _educationEntries.Count >= StructuredCharacterRecords.MaxEducationEntries;
    }

    private void RenumberEducationEntries()
    {
        for (var i = 0; i < _educationEntries.Count; i++)
        {
            _educationEntries[i].Title.Text = Loc.GetString("records-education-number", ("number", i + 1));
            foreach (var field in _educationEntries[i].FieldLabels)
            {
                field.Label.Text = Loc.GetString(field.LocalizationKey) + (i == 0 ? string.Empty : $" ({i + 1})");
            }
        }
    }

    private void UpdateEducationLayout()
    {
        var rowOrientation = FormColumn.Width >= 760
            ? BoxContainer.LayoutOrientation.Horizontal
            : BoxContainer.LayoutOrientation.Vertical;

        ResidenceFirstRow.Orientation = rowOrientation;
        ResidenceSecondRow.Orientation = rowOrientation;
        AcademicTitleFirstRow.Orientation = rowOrientation;

        foreach (var entry in _educationEntries)
        {
            entry.FirstRow.Orientation = rowOrientation;
            entry.SecondRow.Orientation = rowOrientation;
            entry.ThirdRow.Orientation = rowOrientation;
        }
    }

    private void OpenPreview()
    {
        if (_previewWindow?.IsOpen == true)
        {
            _previewWindow.MoveToFront();
            return;
        }

        _previewWindow = new RecordsPreviewWindow();
        _previewWindow.OnClose += () => _previewWindow = null;
        UpdatePreview();
        _previewWindow.FitToScreen(Root?.Size ?? new Vector2(900, 650));
        _previewWindow.OpenCentered();
    }

    private void UpdatePreview()
    {
        if (_previewWindow == null)
            return;

        var noData = Loc.GetString("records-value-no-data");
        var date = GetCurrentBirthDate();
        var identity = new RecordIdentityData(
            ValueOr(NameEdit.Text, noData),
            string.Empty,
            string.Empty,
            string.Empty,
            ValueOr(NameEdit.Text, noData),
            Loc.GetString(RecordSpeciesClassification.IsManufactured(_species)
                ? "records-date-of-manufacture-edit"
                : "records-date-of-birth-edit"),
            ValueOr(date, noData),
            ValueOr(_sexDisplay, noData),
            ValueOr(_speciesDisplay, noData),
            $"{_height} {Loc.GetString("records-height-unit-centimeters")}",
            noData,
            ValueOr(_confederationDisplay, noData),
            ValueOr(CountryEdit.Text, noData));

        _previewWindow.SetRecords(
            RecordViewBuilder.Medical(identity, _medicalStorage, _species, Loc.GetString),
            RecordViewBuilder.Security(identity, _securityStorage, Loc.GetString),
            RecordViewBuilder.Employment(identity, _employmentStorage, Loc.GetString),
            RecordTabs.CurrentTab);
    }

    private string GetCurrentBirthDate()
    {
        var day = BirthDayEdit.Text.Trim();
        var month = BirthMonthEdit.Text.Trim();
        var year = BirthYearEdit.Text.Trim();
        return day.Length == 0 || month.Length == 0 || year.Length == 0
            ? string.Empty
            : $"{day}.{month}.{year}";
    }

    private static string ValueOr(string value, string fallback) =>
        string.IsNullOrWhiteSpace(value) ? fallback : value.Trim();

    private void PopulateBooleanOptions(RecordOptionButton button)
    {
        button.AddItem(Loc.GetString("records-value-no"), 0);
        button.AddItem(Loc.GetString("records-value-yes"), 1);
        button.SelectId(0);
    }

    private void BindDatePart(LineEdit edit, int maxLength, Action callback)
    {
        edit.OnTextChanged += _ =>
        {
            if (_updating)
                return;

            var sanitized = new string(edit.Text
                .Where(character => character is >= '0' and <= '9')
                .Take(maxLength)
                .ToArray());
            if (edit.Text != sanitized)
            {
                _updating = true;
                edit.Text = sanitized;
                edit.CursorPosition = Math.Min(edit.CursorPosition, sanitized.Length);
                _updating = false;
            }

            callback();
        };
    }

    private static void BindLineEdit(LineEdit edit, Action callback)
    {
        edit.OnTextChanged += _ => callback();
    }

    private static void BindTextEdit(RecordTextEdit edit, Action callback)
    {
        edit.OnTextChanged += _ => callback();
    }

    private void PopulateEnumOptions<T>(RecordOptionButton button, IEnumerable<T> values, string keyPrefix) where T : struct, Enum
    {
        foreach (var value in values)
            button.AddItem(
                Loc.GetString($"{keyPrefix}-{value.ToString().ToLowerInvariant()}"),
                value.GetHashCode());
        button.SelectId(0);
    }

    protected override void ExitedTree()
    {
        base.ExitedTree();

        _previewWindow?.Close();
        _previewWindow = null;
    }

    private static string GetText(RecordTextEdit edit) => Rope.Collapse(edit.TextRope).Trim();
    private static void SetText(RecordTextEdit edit, string value) => edit.TextRope = new Rope.Leaf(value);

