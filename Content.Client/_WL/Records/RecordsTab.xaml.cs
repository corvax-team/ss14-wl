    public void SetResidenceRegions(IEnumerable<(string DisplayName, Texture? Icon)> regions, Texture? otherIcon)
    {
        _residenceConfederationValues.Clear();
        SecurityResidenceConfederation.Clear();

        foreach (var (displayName, icon) in regions.DistinctBy(region => region.DisplayName))
        {
            _residenceConfederationValues.Add(displayName);
            var id = _residenceConfederationValues.Count - 1;
            if (icon == null)
                SecurityResidenceConfederation.AddItem(displayName, id);
            else
                SecurityResidenceConfederation.AddItem(icon, displayName, id);
        }

        _residenceConfederationValues.Add(string.Empty);
        var otherId = _residenceConfederationValues.Count - 1;
        var other = Loc.GetString("records-residence-confederation-other");
        if (otherIcon == null)
            SecurityResidenceConfederation.AddItem(other, otherId);
        else
            SecurityResidenceConfederation.AddItem(otherIcon, other, otherId);

        SecurityResidenceConfederation.SelectId(otherId);
        UpdateResidenceCustomVisibility();
    }

    public void SetRecords(
        string medicalStorage,
        string securityStorage,
        string employmentStorage,
        string species,
        string speciesDisplay,
        string sexDisplay,
        string confederationDisplay,
        string fullName,
        string country,
        string storedDateOfBirth,
        int age,
        int height)
    {
        _updating = true;
        _characterAge = age;
        _species = species;
        _speciesDisplay = speciesDisplay;
        _sexDisplay = sexDisplay;
        _confederationDisplay = confederationDisplay;
        _height = height;
        _medicalStorage = medicalStorage;
        _securityStorage = securityStorage;
        _employmentStorage = employmentStorage;
        NameEdit.Text = fullName;
        CountryEdit.Text = country;
        SetMedical(StructuredCharacterRecords.ReadMedical(medicalStorage));
        SetSecurity(StructuredCharacterRecords.ReadSecurity(securityStorage));
        SetEmployment(StructuredCharacterRecords.ReadEmployment(employmentStorage));
        var normalizedDateOfBirth = SetDateOfBirth(storedDateOfBirth);
        var organic = RecordSpeciesClassification.IsOrganic(species);
        var manufactured = RecordSpeciesClassification.IsManufactured(species);
        MedicalProcedureFields.Visible = organic || manufactured;
        MedicalProceduresLabel.Text = Loc.GetString(manufactured
            ? "records-repair-records"
            : "records-surgeries");
        OrganicMedicalFields.Visible = organic;
        BirthDateLabel.Text = Loc.GetString(manufactured
            ? "records-date-of-manufacture-edit"
            : "records-date-of-birth-edit");
        _updating = false;
        UpdatePreview();
        UpdateEducationLayout();

        if (normalizedDateOfBirth != null && normalizedDateOfBirth != storedDateOfBirth)
            OnGeneralRecordAgeChanged?.Invoke(normalizedDateOfBirth);
    }

    private string? SetDateOfBirth(string storedDate)
    {
        if (WLCalendar.TryParseBirthDate(storedDate, out var birthDate))
        {
            birthDate = WLCalendar.RecalculateBirthDate(_characterAge, birthDate);
            BirthDayEdit.Text = birthDate.Day.ToString("00");
            BirthMonthEdit.Text = birthDate.Month.ToString("00");
            BirthYearEdit.Text = birthDate.Year.ToString("0000");
            BirthDateValidationLabel.Visible = false;
            return WLCalendar.FormatBirthDate(birthDate);
        }

        BirthDayEdit.Text = string.Empty;
        BirthMonthEdit.Text = string.Empty;
        BirthYearEdit.Text = string.Empty;
        BirthDateValidationLabel.Visible = !string.IsNullOrWhiteSpace(storedDate);
        BirthDateValidationLabel.Text = Loc.GetString("records-date-of-birth-legacy-invalid", ("date", storedDate));
        return null;
    }

    private void UpdateBirthDate()
    {
        if (_updating)
            return;

        var dayText = BirthDayEdit.Text.Trim();
        var monthText = BirthMonthEdit.Text.Trim();
        if (dayText.Length == 0 && monthText.Length == 0)
        {
            BirthYearEdit.Text = string.Empty;
            BirthDateValidationLabel.Visible = false;
            OnGeneralRecordAgeChanged?.Invoke(string.Empty);
            UpdatePreview();
            return;
        }

        if (!int.TryParse(dayText, out var day) ||
            !int.TryParse(monthText, out var month) ||
            !WLCalendar.TryCreateBirthDate(_characterAge, day, month, out var birthDate))
        {
            BirthYearEdit.Text = string.Empty;
            BirthDateValidationLabel.Text = Loc.GetString("records-date-of-birth-invalid");
            BirthDateValidationLabel.Visible = dayText.Length > 0 && monthText.Length > 0;
            UpdatePreview();
            return;
        }

        BirthYearEdit.Text = birthDate.Year.ToString("0000");
        BirthDateValidationLabel.Visible = false;
        OnGeneralRecordAgeChanged?.Invoke(WLCalendar.FormatBirthDate(birthDate));
        UpdatePreview();
    }

    private void SetMedical(MedicalRecordData record)
    {
        MedicalWeight.Text = record.Weight;
        MedicalPostmortem.Text = record.PostmortemInstructions;
        MedicalDnr.SelectId(record.DoNotResuscitate ? 1 : 0);
        MedicalRefusedTreatment.Text = record.RefusedTreatment;
        MedicalEmergencyContact.Text = record.EmergencyContact;
        SetText(MedicalSurgeries, record.Surgeries);
        SetText(MedicalMedication, record.Medication);
        SetText(MedicalPhysiological, record.PhysiologicalNotes);
        SetText(MedicalPsychological, record.PsychologicalNotes);
        SetText(MedicalNotes, record.Notes);
        MedicalLastUpdated.SetText(record.LastUpdated);
    }

    private void SetSecurity(SecurityRecordData record)
    {
        var residence = StructuredCharacterRecords.ReadResidence(record.Residence);
        var confederationIndex = _residenceConfederationValues.FindIndex(value =>
            !string.IsNullOrEmpty(value) && value == residence.Confederation);
        if (confederationIndex < 0)
        {
            confederationIndex = _residenceConfederationValues.FindIndex(string.IsNullOrEmpty);
            SecurityResidenceCustom.Text = residence.Confederation;
        }
        else
        {
            SecurityResidenceCustom.Text = string.Empty;
        }

        SecurityResidenceConfederation.SelectId(confederationIndex);
        SecurityResidencePlanet.Text = residence.Planet;
        SecurityResidenceStreet.Text = residence.Street;
        SecurityResidenceUnit.Text = residence.Unit;
        SecurityResidenceDetails.Text = residence.Details;
        UpdateResidenceCustomVisibility();
        SecurityFeatures.Text = record.IdentifyingFeatures;
        SecurityMaritalStatus.SelectId((int) record.MaritalStatus);
        SecurityRelatives.Text = record.CloseRelatives;
        SecurityEmergencyContact.Text = record.EmergencyContact;
        SetText(SecurityPermits, record.Permits);
        SecuritySupervision.SelectId(record.UnderSecuritySupervision ? 1 : 0);
        SetText(SecurityArrests, record.ArrestHistory);
        SetText(SecurityImprisonment, record.ImprisonmentHistory);
        SetText(SecurityNotes, record.Notes);
        SecurityLastUpdated.SetText(record.LastUpdated);
    }

    private void SetEmployment(EmploymentRecordData record)
    {
        foreach (var entry in _educationEntries)
            entry.Container.Orphan();
        _educationEntries.Clear();

        foreach (var education in record.Education)
            AddEducationEntry(education, false);

        EmploymentAcademicTitle.SelectId((int) record.AcademicTitle);
        EmploymentAcademicTitleField.Text = record.AcademicTitleField;
        EmploymentAcademicTitleDate.SetText(record.AcademicTitleDate);
        UpdateAcademicTitleVisibility(false);
        SetText(EmploymentLicenses, record.Licenses);
        SetText(EmploymentHistory, record.EmploymentHistory);
        SetText(EmploymentNotes, record.Notes);
        EmploymentLastUpdated.SetText(record.LastUpdated);
        UpdateEducationButton();
    }

    private void EmitMedical()
    {
        if (_updating)
            return;

        _medicalStorage = StructuredCharacterRecords.WriteMedical(new MedicalRecordData
        {
            Weight = MedicalWeight.Text,
            PostmortemInstructions = MedicalPostmortem.Text,
            DoNotResuscitate = MedicalDnr.SelectedId == 1,
            RefusedTreatment = MedicalRefusedTreatment.Text,
            EmergencyContact = MedicalEmergencyContact.Text,
            Surgeries = GetText(MedicalSurgeries),
            Medication = GetText(MedicalMedication),
            PhysiologicalNotes = GetText(MedicalPhysiological),
            PsychologicalNotes = GetText(MedicalPsychological),
            Notes = GetText(MedicalNotes),
            LastUpdated = MedicalLastUpdated.Text,
        });
        OnMedicalRecordChanged?.Invoke(_medicalStorage);
        UpdatePreview();
    }

    private void EmitSecurity()
    {
        if (_updating)
            return;

        _securityStorage = StructuredCharacterRecords.WriteSecurity(new SecurityRecordData
        {
            Residence = StructuredCharacterRecords.WriteResidence(new ResidenceRecordData
            {
                Confederation = GetSelectedResidenceConfederation(),
                Planet = SecurityResidencePlanet.Text,
                Street = SecurityResidenceStreet.Text,
                Unit = SecurityResidenceUnit.Text,
                Details = SecurityResidenceDetails.Text,
            }),
            IdentifyingFeatures = SecurityFeatures.Text,
            MaritalStatus = (RecordMaritalStatus) SecurityMaritalStatus.SelectedId,
            CloseRelatives = SecurityRelatives.Text,
            EmergencyContact = SecurityEmergencyContact.Text,
            Permits = GetText(SecurityPermits),
            UnderSecuritySupervision = SecuritySupervision.SelectedId == 1,
            ArrestHistory = GetText(SecurityArrests),
            ImprisonmentHistory = GetText(SecurityImprisonment),
            Notes = GetText(SecurityNotes),
            LastUpdated = SecurityLastUpdated.Text,
        });
        OnSecurityRecordChanged?.Invoke(_securityStorage);
        UpdatePreview();
    }

    private void UpdateResidenceCustomVisibility()
    {
        ResidenceCustomRow.Visible = IsCustomResidenceSelected();
    }

    private bool IsCustomResidenceSelected()
    {
        return TryGetSelectedResidenceConfederation(out var confederation) &&
               string.IsNullOrEmpty(confederation);
    }

    private string GetSelectedResidenceConfederation()
    {
        if (!TryGetSelectedResidenceConfederation(out var confederation))
            return string.Empty;

        return string.IsNullOrEmpty(confederation)
            ? SecurityResidenceCustom.Text
            : confederation;
    }

    private bool TryGetSelectedResidenceConfederation(out string confederation)
    {
        var selected = SecurityResidenceConfederation.SelectedId;
        if (selected < 0 || selected >= _residenceConfederationValues.Count)
        {
            confederation = string.Empty;
            return false;
        }

        confederation = _residenceConfederationValues[selected];
        return true;
    }

    private void EmitEmployment()
    {
        if (_updating)
            return;

        var hasAcademicTitle = EmploymentAcademicTitle.SelectedId != (int) RecordAcademicTitle.NotApplicable;
        var record = new EmploymentRecordData
        {
            AcademicTitle = (RecordAcademicTitle) EmploymentAcademicTitle.SelectedId,
            AcademicTitleField = hasAcademicTitle ? EmploymentAcademicTitleField.Text : string.Empty,
            AcademicTitleDate = hasAcademicTitle ? EmploymentAcademicTitleDate.Text : string.Empty,
            Licenses = GetText(EmploymentLicenses),
            EmploymentHistory = GetText(EmploymentHistory),
            Notes = GetText(EmploymentNotes),
            LastUpdated = EmploymentLastUpdated.Text,
        };

        foreach (var entry in _educationEntries)
        {
            record.Education.Add(new EducationRecordData
            {
                Specialty = entry.Specialty.Text,
                SpecialtyGroup = entry.SpecialtyGroupValues[entry.SpecialtyGroup.SelectedId],
                SpecialtySubgroup = entry.SpecialtySubgroupValues[entry.SpecialtySubgroup.SelectedId],
                Degree = (RecordAcademicDegree) entry.Degree.SelectedId,
                Institution = entry.Institution.Text,
                DiplomaDate = entry.DiplomaDate.Text,
            });
        }

        _employmentStorage = StructuredCharacterRecords.WriteEmployment(record);
        OnEmploymentRecordChanged?.Invoke(_employmentStorage);
        UpdatePreview();
    }

