using System.Linq;
using Content.Client._WL.Records;
using Content.Client.UserInterface.Controls;
using Content.Shared._WL.Compromise;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.XAML;
using Robust.Client.GameObjects;
using Robust.Client.UserInterface.Controls;
using Robust.Shared.Prototypes;
using Robust.Shared.Utility;

namespace Content.Client.FlavorText
{
    [GenerateTypedNameReferences]
    public sealed partial class FlavorText : Control
    {
        public Action<string>? OnFlavorTextChanged;

        // WL-Changes: Start
        public Action<string>? OnOocTextChanged;
        public Action<string>? OnCompromiseTextChanged;

        public Action<string, string>? OnCompromiseSelected;

        private Dictionary<ProtoId<CompromiseCategoryPrototype>, List<ProtoId<CompromisePrototype>>> _compromises = new();

        [Dependency] private IPrototypeManager _protoMan = default!;
        [Dependency] private IEntityManager _entMan = default!;

        private readonly SpriteSystem _sprite;
        // WL-Changes: End

        public FlavorText()
        {
            RobustXamlLoader.Load(this);
            IoCManager.InjectDependencies(this);

            var loc = IoCManager.Resolve<ILocalizationManager>();
            CFlavorTextInput.Placeholder = new Rope.Leaf(loc.GetString("flavor-text-placeholder"));

            // WL-Changes: Start
            _sprite = _entMan.System<SpriteSystem>();

            COocTextInput.Placeholder = new Rope.Leaf(loc.GetString("flavor-tab-ooc-placeholder"));
            COocTextInput.OnTextChanged += _ => OocTextChanged();

            CCompromiseEdit.Placeholder = new Rope.Leaf(loc.GetString("flavor-tab-compromise-placeholder"));
            CCompromiseEdit.OnTextChanged += _ => CompromiseTextChanged();

            UpdateCompromiseButtons();
            // WL-Changes: End

            CFlavorTextInput.OnTextChanged  += _ => FlavorTextChanged();
        }

        public void FlavorTextChanged()
        {
            OnFlavorTextChanged?.Invoke(Rope.Collapse(CFlavorTextInput.TextRope).Trim());
        }

        // WL-Changes: Start
        public void OocTextChanged()
        {
            OnOocTextChanged?.Invoke(Rope.Collapse(COocTextInput.TextRope).Trim());
        }

        public void CompromiseTextChanged()
        {
            OnCompromiseTextChanged?.Invoke(Rope.Collapse(CCompromiseEdit.TextRope).Trim());
        }

        public void CompromiseSelected(ProtoId<CompromiseCategoryPrototype> category, int id)
        {
            if (!_compromises.TryGetValue(category, out var list) ||
                    list.Count - 1 < id)
                return;

            OnCompromiseSelected?.Invoke(category, list[id]);
        }

        public void UpdateCompromiseButtons(Dictionary<ProtoId<CompromiseCategoryPrototype>, ProtoId<CompromisePrototype>>? data = null)
        {
            data ??= new();

            Compromises.Children.Clear();
            _compromises.Clear();

            var compromateCategories = _protoMan
                .EnumeratePrototypes<CompromiseCategoryPrototype>()
                .OrderBy(category => category.Order);

            foreach (var category in compromateCategories)
            {
                var compromisesList = new List<ProtoId<CompromisePrototype>>();

                if (!_compromises.TryAdd(category.ID, compromisesList))
                    continue;

                var name = category.LocalizedName;

                var categoryButton = new RecordOptionButton()
                {
                    HorizontalExpand = true,
                    MinWidth = 80,
                    MaxWidth = 360,
                    Margin = new Thickness(5)
                };

                var compromises = _protoMan
                    .EnumeratePrototypes<CompromisePrototype>()
                    .Where(compromise => compromise.Category == category.ID)
                    .OrderBy(compromise => compromise.Order)
                    .ToList();

                if (compromises.Count == 0)
                    continue;

                for (var i = 0; i < compromises.Count; i++)
                {
                    var compromise = compromises[i];

                    compromisesList.Add(compromise.ID);

                    if (compromise.Icon is { } path)
                        categoryButton.AddItem(_sprite.Frame0(new SpriteSpecifier.Texture(path)), compromise.LocalizedName, i);
                    else
                        categoryButton.AddItem(compromise.LocalizedName, i);

                    var defaultComp = category.DefaultCompromise;

                    if (data.TryGetValue(category.ID, out var dataCompromise))
                        defaultComp = dataCompromise;

                    if (compromise.ID == defaultComp)
                    {
                        CompromiseSelected(category.ID, i);
                        categoryButton.SelectId(i);
                    }
                }

                categoryButton.OnItemSelected += args =>
                {
                    CompromiseSelected(category.ID, args.Id);
                    categoryButton.SelectId(args.Id);
                };

                var box = new BoxContainer()
                {
                    Orientation = BoxContainer.LayoutOrientation.Horizontal,
                    Margin = new Thickness(5),
                    Children =
                    {
                        new Label()
                        {
                            Text = category.LocalizedName + ":",
                            HorizontalAlignment = HAlignment.Center,
                        },
                        categoryButton
                    }
                };

                Compromises.AddChild(box);
            }
        }
        // WL-Changes: Start
    }
}
