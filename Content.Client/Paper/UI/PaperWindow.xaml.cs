        private void WrapMarkup(string openingTag, string closingTag)
        {
            if (_activeMarkupEditor is not { } input)
                return;

            var lower = input.SelectionLower.Index;
            var upper = input.SelectionUpper.Index;
            var text = Rope.Collapse(input.TextRope);
            var selected = text.Substring(lower, upper - lower);
            input.InsertAtCursor(openingTag + selected + closingTag);

            var innerStart = lower + openingTag.Length;
            var innerEnd = innerStart + selected.Length;
            input.CursorPosition = new TextEdit.CursorPos(innerEnd, TextEdit.LineBreakBias.Top);
            input.SelectionStart = new TextEdit.CursorPos(innerStart, TextEdit.LineBreakBias.Top);
            input.GrabKeyboardFocus();
        }

        private void AddBulletMarkup()
        {
            if (_activeMarkupEditor is not { } input)
                return;

            const string bulletTag = "[bullet]";
            var text = Rope.Collapse(input.TextRope);
            var lower = input.SelectionLower.Index;
            var upper = input.SelectionUpper.Index;
            var lineStart = lower == 0 ? 0 : text.LastIndexOf('\n', lower - 1) + 1;
            var lineEnd = upper;
            if (lower == upper)
            {
                var nextLine = text.IndexOf('\n', upper);
                lineEnd = nextLine < 0 ? text.Length : nextLine;
            }

            var section = text.Substring(lineStart, lineEnd - lineStart);
            var replacement = bulletTag + section.Replace("\n", $"\n{bulletTag}");
            input.CursorPosition = new TextEdit.CursorPos(lineEnd, TextEdit.LineBreakBias.Top);
            input.SelectionStart = new TextEdit.CursorPos(lineStart, TextEdit.LineBreakBias.Top);
            input.InsertAtCursor(replacement);
            input.GrabKeyboardFocus();
        }

        private void ToggleColorPalette()
        {
            if (_activeMarkupEditor == null)
                return;

            if (_colorPalette == null)
            {
                _colorPalette = new PaletteColorPicker();
                _colorPalette.PaletteList.OnItemSelected += args =>
                {
                    if (args.ItemList.GetSelected().FirstOrDefault()?.Metadata is not Color color)
                        return;

                    ApplyMarkupColor(color);
                    _colorPalette.Close();
                };
            }

            if (_colorPalette.IsOpen)
                _colorPalette.Close();
            else
                _colorPalette.OpenCenteredLeft();
        }

        private void ApplyMarkupColor(Color color)
        {
            WrapMarkup($"[color={color.ToHexNoAlpha()}]", "[/color]");
        }

