        /// <summary>
        ///     Initialize the paper contents, i.e. the text typed by the
        ///     user and any stamps that have peen put on the page.
        /// </summary>
        public void Populate(PaperComponent.PaperBoundUserInterfaceState state, bool isEditor)
        {
            bool isEditing = state.Mode == PaperComponent.PaperAction.Write && isEditor;
            // WL-Changes-StructuredPaper-Start
            var isStructured = state.Elements != null;
            var isFreeTextEditing = isEditing && state.EditAccess == PaperEditAccess.FreeText;
            var isFieldEditing = isEditing && state.EditAccess == PaperEditAccess.Fields;
            var isFullEditing = isEditing && state.EditAccess == PaperEditAccess.Full;
            if (!isEditing)
                _appendingText = false;
            var isAppendingText = isFieldEditing && _appendingText;
            var isDraftEditing = isFreeTextEditing || isAppendingText;
            _structuredTextLength = state.Elements?.Sum(element =>
                element.Text.Length + element.PreviousText.Length +
                element.Revisions.Sum(revision => revision.Text.Length) +
                (element.NewLineAfter ? 1 : 0))
                ?? state.Text.Length;
            _freeTextLengthOffset = isFreeTextEditing && state.Text.Length > 0
                ? state.Text.Length + (state.Text.EndsWith('\n') ? 0 : 1)
                : isAppendingText && MaxInputLength >= 0
                    ? MaxInputLength - Math.Min(
                        StructuredPaperElement.DefaultMultilineMaxLength,
                        Math.Max(0, MaxInputLength - _structuredTextLength -
                            (state.Elements is { Count: > 0 } && !state.Elements[^1].NewLineAfter ? 1 : 0)))
                    : 0;
            // WL-Changes-StructuredPaper-End
            bool wasEditing = InputContainer.Visible;
            InputContainer.Visible = false; // WL-Changes: Structured paper forms
            EditButtons.Visible = false; // WL-Changes: Structured paper forms
            // WL-Changes-StructuredPaper-Start
            var editorMode = isFullEditing || isDraftEditing;
            if (editorMode && (!_fullEditorActive || _fullEditorAppendMode != isDraftEditing))
            {
                SetFullEditorPreview(false);
                PopulateFullEditor(state, isDraftEditing);
            }

            var showingPreview = editorMode && _previewingStructure;
            StructuredDocumentContainer.Visible = showingPreview || isStructured && !isFullEditing;
            FullEditorContainer.Visible = editorMode && !showingPreview;
            var editorTopMargin = isDraftEditing && state.Elements is { Count: > 0 } &&
                state.Elements[^1].Type == StructuredPaperElementType.StaticText
                    ? 2f
                    : 0f;
            FullEditorContainer.Margin = new Thickness(4, editorTopMargin, 4, 0);
            FullEditorToolbar.Visible = editorMode;
            FullEditorFormattingToolbar.Visible = editorMode && !showingPreview;
            UpdateWindowHeight(editorMode && !showingPreview, false, false);
            var displayedElements = isDraftEditing && !showingPreview
                ? BuildAppendBase(state.Elements)
                : state.Elements;
            PopulateStructuredDocument(showingPreview ? BuildFullEditorPreview() : displayedElements,
                isFieldEditing && !showingPreview);
            _fullEditorActive = editorMode;
            // WL-Changes-StructuredPaper-End

            // For premade documents, we want to be able to edit them rather than
            // replace them.
            if (!wasEditing && isFreeTextEditing)
            {
                // We can get repeated messages with state.Mode == Write if another
                // player opens the UI for reading. In this case, don't update the
                // text input, as this player is currently writing new text and we
                // don't want to lose any text they already input.
                Input.TextRope = Rope.Leaf.Empty;
                Input.CursorPosition = new TextEdit.CursorPos();
            }
            UpdateFillState();

            if (!isStructured)
            {
                var msg = new FormattedMessage();
                msg.AddMarkupPermissive(state.Text);
                for (var i = 0; i <= state.StampedBy.Count * 3 + 1; i++)
                    msg.AddMarkupPermissive("\r\n");

                WrittenTextLabel.SetMessage(msg, UserFormattableTags.BaseAllowedTags, _writtenTextColor);
            }

            WrittenTextLabel.Visible = !showingPreview && !isStructured && state.Text.Length > 0 &&
                (!isEditing || isFreeTextEditing); // WL-Changes: Structured paper forms
            BlankPaperIndicator.Visible = !isEditing &&
                (!isStructured && state.Text.Length == 0 || isStructured && state.Elements!.Count == 0); // WL-Changes: Structured paper forms

            StampDisplay.RemoveAllChildren();
            StampDisplay.RemoveStamps();
            foreach(var stamper in state.StampedBy)
            {
                // WL-Changes-start
                var stamp = new StampWidget();
                stamp.UpdateVisuals(stamper);

                StampDisplay.AddStamp(stamp);
                // WL-Changes-end
            }
        }

        // WL-Changes-StructuredPaper-Start
        private void PopulateStructuredDocument(List<StructuredPaperElement>? elements, bool editingFields)
        {
            _fieldsEditable = editingFields;

            var canReuseLayout = elements != null &&
                _renderedDocumentEditable == editingFields &&
                CanReuseStructuredDocument(elements);

            if (canReuseLayout)
            {
                UpdateStructuredFields(elements!, editingFields);
                return;
            }

            if (IsOpen && !canReuseLayout && _renderedElements == null)
                PrepareForFirstReveal();

            StructuredDocumentContainer.RemoveAllChildren();
            _fieldControls.Clear();
            _renderedFields.Clear();
            _renderedElements = elements?.Select(element => element.Copy()).ToList();
            _renderedDocumentEditable = editingFields;
            if (elements == null)
                return;

            var label = new RichTextLabel
            {
                HorizontalExpand = true,
                VerticalAlignment = Control.VAlignment.Top,
                StyleClasses = { "PaperWrittenText" },
            };

            label.SetMessage(BuildStructuredMessage(elements, editingFields), StructuredPaperAllowedTags, _writtenTextColor);
            StructuredDocumentContainer.AddChild(label);
            RegisterStructuredFieldControls(label);
            UpdateStructuredFields(elements, editingFields);
        }

        private void UpdateStructuredFields(IReadOnlyList<StructuredPaperElement> elements, bool editingFields)
        {
            _renderedFields.Clear();
            foreach (var element in elements)
            {
                if (!IsFillableField(element.Type))
                    continue;

                _renderedFields[element.Id] = element.Copy();
                if (!_fieldControls.TryGetValue(element.Id, out var field))
                    continue;

                field.UpdateContent(
                    element.Text,
                    GetRevisions(element),
                    Loc.GetString("paper-ui-form-write-field"),
                    editingFields,
                    element.Id == _editingFieldId,
                    element.HandwritingStyle,
                    element.Type == StructuredPaperElementType.Signature &&
                    !_previewingStructure);
            }

            _renderedElements = elements.Select(element => element.Copy()).ToList();

        }

        private static IReadOnlyList<PaperFieldRevision> GetRevisions(StructuredPaperElement element)
        {
            if (string.IsNullOrWhiteSpace(element.PreviousText))
                return element.Revisions;

            var revisions = element.Revisions.Select(revision => revision.Copy()).ToList();
            revisions.Add(new PaperFieldRevision(element.PreviousText, element.PreviousHandwritingStyle));
            return revisions;
        }

        private bool CanReuseStructuredDocument(IReadOnlyList<StructuredPaperElement> elements)
        {
            if (_renderedElements == null)
                return false;

            if (_renderedElements.Count != elements.Count)
                return false;

            for (var i = 0; i < elements.Count; i++)
            {
                var previous = _renderedElements[i];
                var current = elements[i];
                if (previous.Id != current.Id ||
                    previous.Type != current.Type ||
                    previous.NewLineAfter != current.NewLineAfter ||
                    previous.MaxLength != current.MaxLength ||
                    !IsFillableField(current.Type) && previous.Text != current.Text)
                {
                    return false;
                }
            }

            return true;
        }

        private FormattedMessage BuildStructuredMessage(List<StructuredPaperElement> elements, bool editable)
        {
            var message = new FormattedMessage();

            foreach (var element in elements)
            {
                if (element.Type == StructuredPaperElementType.StaticText)
                {
                    message.AddMarkupPermissive(element.Text);
                }
                else if (element.Type == StructuredPaperElementType.HandwrittenText)
                {
                    StructuredPaperFieldControl.AddHandwriting(message, element.Text, element.HandwritingStyle, true);
                }
                else
                {
                    _renderedFields[element.Id] = element.Copy();
                    var attributes = new Dictionary<string, MarkupParameter>
                    {
                        ["text"] = new(element.Text),
                        ["previous"] = new(element.PreviousText),
                        ["placeholder"] = new(Loc.GetString("paper-ui-form-write-field")),
                        ["editable"] = new(editable ? 1 : 0),
                        ["selected"] = new(element.Id == _editingFieldId ? 1 : 0),
                        ["multiline"] = new(element.Type == StructuredPaperElementType.MultilineField ? 1 : 0),
                        ["signature"] = new(element.Type == StructuredPaperElementType.Signature ? 1 : 0),
                        ["signature-action"] = new(element.Type == StructuredPaperElementType.Signature &&
                            !_previewingStructure ? 1 : 0),
                        ["style"] = new((long) element.HandwritingStyle),
                        ["previous-style"] = new((long) element.PreviousHandwritingStyle),
                    };

                    message.PushTag(new MarkupNode(StructuredPaperFieldTag.TagName, new MarkupParameter(element.Id), attributes), true);
                }

                if (element.NewLineAfter)
                    message.PushNewline();
            }

            if (editable)
            {
                if (elements.Count > 0 && !elements[^1].NewLineAfter)
                    message.PushNewline();

                message.PushTag(new MarkupNode(StructuredPaperAppendTag.TagName), true);
            }

            return message;
        }

        private void RegisterStructuredFieldControls(RichTextLabel label)
        {
            foreach (var control in label.Controls)
            {
                if (control is StructuredPaperAppendControl append)
                {
                    append.OnPressed += _ => OpenAppendEditor();
                    continue;
                }

                if (control is not StructuredPaperFieldControl field)
                    continue;

                _fieldControls[field.FieldId] = field;
                var fieldId = field.FieldId;
                field.OnPressed += _ =>
                {
                    if (_renderedFields.TryGetValue(fieldId, out var current))
                    {
                        if (_fieldsEditable)
                            OpenFieldEditor(current, field);
                        else
                            RequestFieldEditor(fieldId, field);
                    }
                };
                field.OnSignatureRequested += () => OnSignatureRequested?.Invoke(fieldId);

                if (fieldId == _editingFieldId)
                {
                    _activeFieldControl = field;
                    field.SetSelected(true);
                }

            }

            UpdateStructuredFieldWidths();
        }

        private void UpdateStructuredFieldWidths()
        {
            var availableWidth = StructuredDocumentContainer.Width - 8;
            if (availableWidth <= 0)
                return;

            foreach (var field in _fieldControls.Values)
                field.SetDocumentWidth(availableWidth);
        }

        private void RequestFieldEditor(string fieldId, StructuredPaperFieldControl field)
        {
            if (!_renderedFields.TryGetValue(fieldId, out var element))
                return;

            // The server still authorizes the session and validates the eventual write. Opening the local editor
            // immediately avoids making the interaction wait for a full network round-trip.
            if (CanBeginFieldEdit?.Invoke() == false)
            {
                OnFieldEditRequested?.Invoke(fieldId);
                return;
            }

            CloseFieldEditor();
            _editingFieldId = fieldId;
            _activeFieldControl = field;
            field.SetSelected(true);
            OpenFieldEditor(element, field);
        }

        private void OpenFieldEditor(StructuredPaperElement element, StructuredPaperFieldControl field)
        {
            CloseFieldEditor();
            _appendingText = false;
            _editingFieldId = element.Id;
            _activeFieldControl = field;
            field.SetSelected(true);

            var remainingPaperLength = MaxInputLength < 0
                ? int.MaxValue
                : Math.Max(0, MaxInputLength - _structuredTextLength + element.Text.Length);
            var maxLength = Math.Min(element.GetMaxLength(), remainingPaperLength);
            _fieldEditor.OpenField(element.Type, element.Text, maxLength);
        }

        private void OpenAppendEditor()
        {
            CloseFieldEditor();
            _appendingText = true;
            SetFullEditorPreview(false);
            if (MaxInputLength >= 0)
            {
                var separatorLength = _renderedElements is { Count: > 0 } &&
                    !_renderedElements[^1].NewLineAfter
                        ? 1
                        : 0;
                var availableLength = Math.Min(
                    StructuredPaperElement.DefaultMultilineMaxLength,
                    Math.Max(0, MaxInputLength - _structuredTextLength - separatorLength));
                _freeTextLengthOffset = MaxInputLength - availableLength;
            }
            _fullEditorAppendMode = true;
            _previewBaseLegacy = false;
            _previewBaseElements.Clear();
            if (_renderedElements != null)
                _previewBaseElements.AddRange(_renderedElements.Select(element => element.Copy()));
            _editorCodec = StructuredPaperEditorCodec.Create([], true, out _fullEditorSource);
            RebuildFullEditor();
            _fullEditorActive = true;
            FullEditorContainer.Visible = true;
            FullEditorToolbar.Visible = true;
            FullEditorFormattingToolbar.Visible = true;
            UpdateWindowHeight(true, false, false);
            UserInterfaceManager.DeferAction(() =>
            {
                ScrollingContents.VScrollTarget = float.PositiveInfinity;
            });
        }

        private void CloseFieldEditor()
        {
            var wasAppending = _appendingText;
            if (_activeFieldControl != null &&
                _editingFieldId != null)
            {
                _activeFieldControl.SetSelected(false);
            }

            _activeFieldControl = null;
            _editingFieldId = null;
            _appendingText = false;
            if (wasAppending)
            {
                FullEditorContainer.Visible = false;
                FullEditorToolbar.Visible = false;
                FullEditorFormattingToolbar.Visible = false;
                UpdateWindowHeight(false, false, false);
                SetActiveMarkupEditor(null);
            }
        }

        private void PopulateFullEditor(PaperComponent.PaperBoundUserInterfaceState? state, bool appendOnly = false)
        {
            _fullEditorAppendMode = appendOnly;
            _previewBaseElements.Clear();
            _previewBaseLegacy = appendOnly && state?.Elements == null && !string.IsNullOrEmpty(state?.Text);
            if (appendOnly && state?.Elements != null)
                _previewBaseElements.AddRange(state.Elements.Select(element => element.Copy()));
            else if (_previewBaseLegacy)
                _previewBaseElements.Add(new StructuredPaperElement(
                    "preview-legacy",
                    StructuredPaperElementType.StaticText,
                    state!.Text,
                    newLineAfter: !state.Text.EndsWith('\n')));

            var incoming = appendOnly
                ? new List<StructuredPaperElement>
                {
                    new(string.Empty, StructuredPaperElementType.HandwrittenText, string.Empty)
                    {
                        HandwritingStyle = HandwritingStyle,
                    },
                }
                : state?.Elements ?? new List<StructuredPaperElement>
                {
                    new(string.Empty, StructuredPaperElementType.StaticText, state?.Text ?? string.Empty),
                };

            if (incoming.Count == 0)
                incoming.Add(new StructuredPaperElement(string.Empty, StructuredPaperElementType.StaticText, string.Empty));

            _editorCodec = StructuredPaperEditorCodec.Create(incoming, appendOnly, out _fullEditorSource);
            RebuildFullEditor();
        }

        private static List<StructuredPaperElement>? BuildAppendBase(
            IReadOnlyList<StructuredPaperElement>? elements)
        {
            if (elements == null)
                return null;

            var displayed = elements.Select(element => element.Copy()).ToList();
            if (displayed.Count > 0)
                displayed[^1].NewLineAfter = false;

            return displayed;
        }

        private void ToggleFullEditorPreview()
        {
            SetFullEditorPreview(PreviewStructureButton.Pressed);
        }

        private void SetFullEditorPreview(bool preview)
        {
            _previewingStructure = preview;
            PreviewStructureButton.Pressed = preview;
            AddSingleLineFieldButton.Disabled = preview;
            AddMultilineFieldButton.Disabled = preview;
            AddSignatureButton.Disabled = preview || _activeMarkupEditor == null;
            if (!_fullEditorActive)
                return;

            if (preview)
            {
                PopulateStructuredDocument(BuildFullEditorPreview(), false);
            }
            else if (_fullEditorAppendMode)
            {
                PopulateStructuredDocument(
                    _previewBaseLegacy ? null : BuildAppendBase(_previewBaseElements),
                    _fieldsEditable);
            }

            StructuredDocumentContainer.Visible = preview || _fullEditorAppendMode && !_previewBaseLegacy;
            WrittenTextLabel.Visible = !preview && _fullEditorAppendMode && _previewBaseLegacy;
            FullEditorContainer.Visible = !preview;
            FullEditorFormattingToolbar.Visible = !preview;
            UpdateWindowHeight(!preview, false, false);
        }

        private List<StructuredPaperElement> BuildFullEditorPreview()
        {
            var preview = _fullEditorAppendMode
                ? _previewBaseElements.Select(element => element.Copy()).ToList()
                : new List<StructuredPaperElement>();
            if (!TryParseFullEditor(out var draft))
                return preview;

            if (preview.Count > 0 && draft.Count > 0 && !preview[^1].NewLineAfter)
                preview[^1].NewLineAfter = true;
            preview.AddRange(draft);

            var usedIds = new HashSet<string>();
            for (var i = 0; i < preview.Count; i++)
            {
                if (string.IsNullOrWhiteSpace(preview[i].Id) || !usedIds.Add(preview[i].Id))
                {
                    preview[i].Id = $"preview-{i}";
                    usedIds.Add(preview[i].Id);
                }
            }

            return preview;
        }

        private void SaveFullEditor()
        {
            if (!TryParseFullEditor(out var elements))
                return;

            if (_fullEditorAppendMode)
            {
                _appendingText = false;
                OnElementsAppended?.Invoke(elements);
            }
            else
                OnStructureSaved?.Invoke(elements);
        }

        private void AddFullEditorElement(StructuredPaperElementType type)
        {
            if (_activeMarkupEditor is not { } input)
                return;

            var token = type switch
            {
                StructuredPaperElementType.SingleLineField => "[f]",
                StructuredPaperElementType.MultilineField => "[lf]",
                _ => throw new ArgumentOutOfRangeException(nameof(type)),
            };

            input.InsertAtCursor(token);
            input.GrabKeyboardFocus();
        }

        private void InsertSignatureToken()
        {
            if (_activeMarkupEditor is not { } input)
                return;

            input.InsertAtCursor(SignatureEditorToken);
            input.GrabKeyboardFocus();
        }

        private void RebuildFullEditor()
        {
            SetActiveMarkupEditor(null);
            FullEditorElements.RemoveAllChildren();
            var compact = _fullEditorAppendMode &&
                (_previewBaseLegacy || _previewBaseElements.Count > 0);
            var panel = new PanelContainer
            {
                StyleIdentifier = "PaperEditorBackground",
                HorizontalExpand = true,
                VerticalExpand = !compact,
                Margin = new Thickness(0),
            };
            var input = CreateSourceTextEdit(_fullEditorSource, compact);
            if (_fullEditorAppendMode)
                input.StyleClasses.Add(GetHandwritingEditorClass(HandwritingStyle));
            input.OnTextChanged += _ =>
            {
                _fullEditorSource = Rope.Collapse(input.TextRope);
                if (compact)
                    UpdateTextEditHeight(input, 28f);
                UpdateFullEditorValidation();
            };
            input.OnKeyBindDown += _ => SetActiveMarkupEditor(input);
            panel.AddChild(input);
            FullEditorElements.AddChild(panel);
            SetActiveMarkupEditor(input);
            UpdateFullEditorValidation();
            UserInterfaceManager.DeferAction(() =>
            {
                input.GrabKeyboardFocus();
                if (compact)
                    UpdateTextEditHeight(input, 28f);
            });
        }

        private bool TryParseFullEditor(out List<StructuredPaperElement> elements)
        {
            elements = new List<StructuredPaperElement>();
            return _editorCodec != null &&
                _editorCodec.TryParse(_fullEditorSource, _fullEditorAppendMode, HandwritingStyle, out elements);
        }

        private void UpdateFullEditorValidation()
        {
            var valid = TryParseFullEditor(out var elements);
            var tooLong = false;
            if (valid && MaxInputLength >= 0)
            {
                var length = elements.Sum(element =>
                    element.Text.Length + element.PreviousText.Length +
                    element.Revisions.Sum(revision => revision.Text.Length) +
                    (element.NewLineAfter ? 1 : 0));
                tooLong = length > MaxInputLength - _freeTextLengthOffset;
                valid = !tooLong;
            }

            SaveStructureButton.Disabled = !valid;
            PreviewStructureButton.Disabled = !valid;
            FullEditorValidationStatus.Visible = !valid;
            FullEditorValidationStatus.Text = tooLong
                ? Loc.GetString("paper-ui-form-editor-too-long")
                : Loc.GetString("paper-ui-form-editor-invalid-tags");
            SaveStructureButton.ToolTip = valid
                ? Loc.GetString("paper-ui-form-save-structure-tooltip")
                : FullEditorValidationStatus.Text;
        }

        private static bool IsFillableField(StructuredPaperElementType type)
        {
            return type is StructuredPaperElementType.SingleLineField or
                StructuredPaperElementType.MultilineField or
                StructuredPaperElementType.SignatureField or
                StructuredPaperElementType.Signature;
        }

        private TextEdit CreateSourceTextEdit(string text, bool compact)
        {
            var input = new TextEdit
            {
                HorizontalExpand = true,
                VerticalExpand = !compact,
                MinHeight = compact ? 28 : 560,
                MaxHeight = compact ? 28 : float.NaN,
                Margin = new Thickness(0),
                StyleClasses = { "PaperTextEdit" },
            };
            input.InsertAtCursor(text);
            input.CursorPosition = new TextEdit.CursorPos(0, TextEdit.LineBreakBias.Top);
            if (compact)
                input.OnResized += () => UpdateTextEditHeight(input, 28f);
            return input;
        }

        private void UpdateTextEditHeight(TextEdit input, float minimumHeight = 24f)
        {
            if (input.Width <= 0)
                return;

            var font = input.TryGetStyleProperty<Font>("font", out var styledFont)
                ? styledFont
                : _resCache.GetFont("/Fonts/NotoSans/NotoSans-Regular.ttf", 12);
            var availableWidth = Math.Max(40f, input.Width - 18f);
            var lineCount = 1;
            var lineWidth = 0f;

            foreach (var rune in Rope.EnumerateRunes(input.TextRope))
            {
                if (rune.Value == '\n')
                {
                    lineCount++;
                    lineWidth = 0;
                    continue;
                }

                if (!font.TryGetCharMetrics(rune, 1f, out var metrics))
                    continue;

                if (lineWidth > 0 && lineWidth + metrics.Advance > availableWidth)
                {
                    lineCount++;
                    lineWidth = 0;
                }

                lineWidth += metrics.Advance;
            }

            var height = Math.Max(minimumHeight, lineCount * font.GetLineHeight(1f) + 6f);
            if (MathHelper.CloseTo(input.MinHeight, height))
                return;

            input.MinHeight = height;
            input.MaxHeight = height;
        }

        private void UpdateWindowHeight(bool fullEditing, bool freeTextEditing, bool appendingText)
        {
            if (_hasFixedWritableHeight)
                return;

            var editorChromeHeight = 0f;
            if (fullEditing || freeTextEditing)
                editorChromeHeight += FormattingToolbarHeight;
            if (fullEditing)
                editorChromeHeight += StructureToolbarHeight;
            if (freeTextEditing || appendingText)
                editorChromeHeight += SaveBarHeight;

            MinHeight = editorChromeHeight > 0
                ? DefaultWindowHeight + editorChromeHeight
                : 150f;
            SetHeight = editorChromeHeight > 0
                ? DefaultWindowHeight + editorChromeHeight
                : DefaultWindowHeight;
        }

